#!/usr/bin/env node
/**
 * Regenerates test/coverage-imports-data.js with app UI modules so Istanbul attributes
 * coverage to sources that no unit test imports (they show as 0% covered instead of omitted).
 *
 * Included: glob "elements" and "addons/.../elements" (see `patterns` in this file), minus excludes.
 * Not included: webpack, scripts, plugins, packages, or addon code outside those element trees.
 */
const fs = require('fs');
const path = require('path');
const glob = require('glob');

const root = path.join(__dirname, '..');
const outFile = path.join(root, 'test', 'coverage-imports-data.js');

const patterns = ['elements/**/*.js', 'addons/**/elements/**/*.js'];

// Paths under native ESM (Karma) that cannot be bulk-imported; keep in sync when fixing load issues.
// - nuxeo-platform-3d: glTF scripts are not valid ESM named exports under karma-esm.
// - routing.js: runs Page.js route setup at import time and requires a full Nuxeo.UI app shell.
const EXCLUDE_PREFIXES = ['addons/nuxeo-platform-3d/'];
const EXCLUDE_EXACT = new Set(['elements/routing.js']);

const excludePredicate = (posixPath) =>
  EXCLUDE_PREFIXES.some((prefix) => posixPath.startsWith(prefix)) || EXCLUDE_EXACT.has(posixPath);

const seen = new Set();
for (const pattern of patterns) {
  for (const file of glob.sync(pattern, { cwd: root, nodir: true })) {
    const p = file.replace(/\\/g, '/');
    if (excludePredicate(p)) continue;
    seen.add(p);
  }
}

// Project-root-relative paths (e.g. "elements/...") so the consumer can resolve with `new URL` from
// any test file location (see test/coverage-helpers/coverage-app-modules.test.js).
const relImports = Array.from(seen).sort();

if (relImports.length === 0) {
  // eslint-disable-next-line no-console
  console.error(
    'generate-coverage-imports: matched 0 modules. Expected elements/**/*.js under',
    root,
    '— check CI working directory, sparse checkout, and that this package root includes the elements/ tree.',
  );
  process.exit(1);
}

const banner = `/**
 * AUTO-GENERATED by scripts/generate-coverage-imports.js — do not edit.
 * Re-run: npm run update-coverage-imports (also invoked at the start of the npm test script)
 */
`;

const content = `${banner}export const coverageModulePaths = ${JSON.stringify(relImports, null, 2)};
`;

fs.writeFileSync(outFile, content, 'utf8');
// eslint-disable-next-line no-console
console.log('generate-coverage-imports: wrote %d module paths to test/coverage-imports-data.js', relImports.length);
