/**
 * Optional responseTransformer for @open-wc/karma-esm (not wired in karma.conf.js today).
 *
 * karma-esm can inject parallel `Promise.all([ import(url), ... ])` for test modules; under load,
 * some imports may fail silently and Mocha never sees those suites. This rewriter would force
 * sequential `import()` instead.
 *
 * Current approach: use a single entry file (`test/load-all-tests.js`, built by
 * `scripts/generate-test-load-all.js`) so Karma loads one static graph and this transformer is
 * unnecessary. Keep this file only if you revert to multiple Karma `files` entries and need the
 * sequential workaround again.
 */
module.exports = function karmaEsmSequentialTestImportsTransformer(ctx) {
  const { body } = ctx;
  if (typeof body !== 'string') {
    return { body };
  }
  if (!body.includes('generated by karma-esm to ensure all tests are loaded')) {
    return { body };
  }

  const needle = 'Promise.all([';
  const idx = body.indexOf(needle);
  if (idx === -1) {
    return { body };
  }

  let depth = 1;
  let i = idx + needle.length;
  const startInner = i;
  for (; i < body.length && depth > 0; i += 1) {
    const c = body[i];
    if (c === '[') depth += 1;
    else if (c === ']') depth -= 1;
  }
  if (depth !== 0) {
    return { body };
  }

  const innerEnd = i - 1;
  const afterBracket = body.slice(innerEnd + 1);
  const closeParen = afterBracket.indexOf(')');
  if (closeParen === -1) {
    return { body };
  }

  const afterPromiseAll = innerEnd + 1 + closeParen + 1;
  const tail = body.slice(afterPromiseAll);
  const thenCatch =
    /^\s*\n\s*\.then\(\(\) => window\.__karma__\.loaded\(\)\)\s*\n\s*\.catch\(\(\) => window\.__karma__\.error\(\)\)/;
  const m = tail.match(thenCatch);
  if (!m) {
    return { body };
  }

  const replaceEnd = afterPromiseAll + m[0].length;
  const inner = body.slice(startInner, innerEnd);
  const urls = [...inner.matchAll(/import\('([^']+)'\)/g)].map((x) => x[1]);
  if (urls.length === 0) {
    return { body };
  }

  const replacement = `(async () => {
      const __testUrls = ${JSON.stringify(urls)};
      for (const __href of __testUrls) {
        try {
          await import(__href);
        } catch (e) {
          console.error('Error loading test file: ' + __href.split('?')[0].replace('/base', ''));
          console.error(e && e.stack ? e.stack : e);
        }
      }
      window.__karma__.loaded();
    })()`;

  return { body: body.slice(0, idx) + replacement + body.slice(replaceEnd) };
};
